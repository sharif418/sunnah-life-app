const raw = JSON.parse(readFileSync(new URL("../quran-uthmani.json", import.meta.url), "utf8"));
const surahs = raw.data.surahs;
if (!Array.isArray(surahs) || surahs.length !== 114) {
  console.error(`quran-uthmani.json must contain exactly 114 surahs (found ${surahs?.length})`);
  process.exit(1);
}
if (BN.length !== 114) {
  console.error(`Bengali name table must have 114 entries (found ${BN.length})`);
  process.exit(1);
}

const out = {
  // Human note: generated by scripts/gen-quran-meta.mjs — do not edit by hand.
  generated: new Date().toISOString().slice(0, 10),
  surahs: surahs.map((s, i) => ({
    number: s.number,
    name: s.name,
    nameBn: BN[i][0],
    meaningBn: BN[i][1],
    englishName: s.englishName,
    englishNameTranslation: s.englishNameTranslation,
    revelationType: s.revelationType === "Meccan" ? "মাক্কী" : "মাদানী",
    revelationTypeEn: s.revelationType,
    ayahCount: s.ayahs.length,
  })),
};

writeFileSync(new URL("../quran-meta-bn.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
const total = out.surahs.reduce((a, s) => a + s.ayahCount, 0);
console.log(`wrote quran-meta-bn.json: ${out.surahs.length} surahs, ${total} ayahs total`);
if (total !== 6236) {
  console.error(`expected 6236 total ayahs, got ${total}`);
  process.exit(1);
}
